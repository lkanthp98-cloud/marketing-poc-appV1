import os
import unittest
from unittest.mock import patch
from fastapi.testclient import TestClient
from backend.main import app,store
from backend import genie
from backend.store import DataError, Viewer


class GenieTests(unittest.TestCase):
    def setUp(self):
        self.env=patch.dict(os.environ,{'GENIE_SPACE_ID':'space-123'});self.env.start()
        self.addCleanup(self.env.stop)
        self.user=Viewer('user-a');self.client=TestClient(app)

    def test_sample_answers_query_reference_data_and_do_not_claim_live_ai(self):
        for question in genie.EXAMPLES:
            data=self.client.post('/api/genie/messages',json={'question':question}).json()
            self.assertEqual(data['status'],'COMPLETED')
            self.assertTrue(data['queries'][0]['rows'])
            self.assertIn('not generated by live Genie',data['text'])
        result=self.client.post('/api/genie/messages',json={'question':'Predict an exact revenue figure tomorrow'}).json()
        self.assertEqual(result['queries'],[])
        self.assertIn('Local mode',result['text'])

    def test_start_followup_poll_and_query_result_transport(self):
        with patch.object(genie,'request',return_value={'conversation_id':'conv-1','message_id':'msg-1','message':{'status':'SUBMITTED'}}) as request:
            first=genie.send(store,self.user,'Spend by platform?')
            self.assertEqual(request.call_args.args[2],'/start-conversation')
        message={'status':'COMPLETED','attachments':[{'text':{'content':'Observed USD cost.'}},
            {'attachment_id':'attach-1','query':{'query':'SELECT platform, SUM(spend) FROM curated GROUP BY platform','title':'Spend'}}]}
        result={'statement_response':{'status':{'state':'SUCCEEDED'},'manifest':{'schema':{'columns':[{'name':'platform'},{'name':'spend'}]}},'result':{'data_array':[['google','12.50']]}}}
        with patch.object(genie,'request',side_effect=[message,result]) as request:
            answer=genie.poll(store,self.user,'conv-1','msg-1',first['conversation_key'])
            self.assertEqual(answer['queries'][0]['rows'],[['google','12.50']])
            self.assertTrue(request.call_args.args[2].endswith('/attachments/attach-1/query-result'))
        with patch.object(genie,'request',return_value={'message_id':'msg-2','status':'SUBMITTED'}) as request:
            follow=genie.send(store,self.user,'Only last month','conv-1',first['conversation_key'])
            self.assertEqual(follow['conversation_id'],'conv-1')
            self.assertEqual(request.call_args.args[2],'/conversations/conv-1/messages')

    def test_conversation_cannot_be_reused_by_another_viewer_or_space(self):
        key=genie.proof(self.user,'conv-1')
        with self.assertRaises(DataError):genie.authorize(Viewer('other-user'),'conv-1',key)
        with patch.dict(os.environ,{'GENIE_SPACE_ID':'other-space'}):
            with self.assertRaises(DataError):genie.authorize(self.user,'conv-1',key)
        with self.assertRaises(DataError):genie.safe_id('../another-space')

    def test_live_requires_forwarded_identity_and_never_falls_back_to_samples(self):
        with patch.object(store,'mode','live'):
            self.assertEqual(self.client.post('/api/genie/messages',json={'question':genie.EXAMPLES[0]}).status_code,401)
            with patch.object(genie,'request',side_effect=DataError('Genie denied access',403)):
                response=self.client.post('/api/genie/messages',json={'question':genie.EXAMPLES[0]},headers={'x-forwarded-access-token':'user-a'})
                self.assertEqual(response.status_code,403)

    def test_failed_expired_and_truncated_results_are_explicit(self):
        for status in ['FAILED','CANCELLED','QUERY_RESULT_EXPIRED']:
            self.assertEqual(genie.normalize(store,self.user,{'status':status},'c','m')['status'],status)
        response={'statement_response':{'manifest':{'schema':{'columns':[{'name':'x'}]}},'result':{'data_array':[[i] for i in range(110)]}}}
        message={'status':'COMPLETED','attachments':[{'attachment_id':'a','query':{'query':'SELECT x FROM t'}}]}
        with patch.object(genie,'request',return_value=response):
            query=genie.normalize(store,self.user,message,'c','m')['queries'][0]
            self.assertEqual(len(query['rows']),100);self.assertTrue(query['truncated'])

    def test_blank_oversized_and_missing_space_are_rejected(self):
        for question in ['   ','x'*4001]:
            self.assertIn(self.client.post('/api/genie/messages',json={'question':question}).status_code,[400,422])
        with patch.dict(os.environ,{'GENIE_SPACE_ID':''}):
            with self.assertRaisesRegex(DataError,'Attach a Genie'):genie.space()


if __name__=='__main__':unittest.main()
